/** Smallest byte strings that start like each accepted upload type. */
export const bytes = (head: number[], length = head.length) => Uint8Array.from({ length }, (_, i) => head[i] ?? 0);
export const PDF = bytes([0x25, 0x50, 0x44, 0x46, 0x2d, 0x31, 0x2e, 0x37]);
export const PNG = bytes([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
export const JPEG = bytes([0xff, 0xd8, 0xff, 0xe0]);
export const WEBP = bytes([0x52, 0x49, 0x46, 0x46, 1, 2, 3, 4, 0x57, 0x45, 0x42, 0x50]);
